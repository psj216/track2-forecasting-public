"""## Executive summary (read this first)

Research-only forward volatility term structure on frozen V5.1 worlds.
Historical blocks and their joint draw pairing are generated by V5.1 without
normalizing historical shocks. A bounded, deterministic future gain relaxes
pre-asof 20-day volatility toward long volatility over 63 business days.
F3 returns its original forecast object exactly. Parameters are fixed before
testing and no observed future value is used by this module.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from numpy.typing import NDArray

from .numeric_v1 import NumericForecast


@dataclass(frozen=True)
class TermStructureConfig:
    """One fixed future variance trajectory, not fitted to public outcomes."""

    half_life_business_days: int = 63
    min_gain: float = 0.85
    max_gain: float = 1.15
    min_vol_ratio: float = 0.5
    max_vol_ratio: float = 2.0


V9_B = TermStructureConfig()


def _mean_gain(
    start: int, stop: int, ratio: NDArray[np.float64], half_life: float,
    config: TermStructureConfig,
) -> NDArray[np.float64]:
    """Average prospective scale over an observation-step horizon segment."""
    if stop <= start:
        return np.ones_like(ratio)
    times = np.arange(start, stop, dtype=float)[:, None]
    decay = np.exp(-np.log(2.0) * times / half_life)
    gain = (1 / ratio)[None, :] + (1 - 1 / ratio)[None, :] * decay
    return np.clip(gain, config.min_gain, config.max_gain).mean(axis=0)


def apply_vol_term_structure(
    baseline: NumericForecast,
    assets: list[str],
    family: str,
    config: TermStructureConfig = V9_B,
) -> NumericForecast:
    """Preserve every V5.1 path identity, modifying only future horizon scales."""
    if family == "T2-F3":
        return baseline
    if (config.half_life_business_days < 1 or config.min_gain <= 0
            or config.min_gain > 1 or config.max_gain < 1
            or config.min_vol_ratio <= 0 or config.max_vol_ratio < 1):
        raise ValueError("invalid fixed V9-B term-structure config")
    meta = baseline.metadata
    regime = meta["regime"]
    ratio = np.asarray([regime["vol_ratio_20_long"][asset] for asset in assets], dtype=float)
    ratio = np.clip(ratio, config.min_vol_ratio, config.max_vol_ratio)
    if not np.isfinite(ratio).all():
        raise ValueError("non-finite pre-asof volatility ratio")
    if np.all(ratio == 1):
        return baseline
    observation_period = float(meta["observation_period_business_days"])
    half_life = max(1.0, config.half_life_business_days / observation_period)
    horizons = meta["observation_horizons"]
    anchor = np.asarray([meta["anchor"][asset] for asset in assets], dtype=float)
    drift = np.asarray([meta["daily_drift"][asset] for asset in assets], dtype=float)
    samples = np.empty_like(baseline.samples)
    previous_step = 0
    previous_shock = np.zeros((len(baseline.samples), len(assets)))
    accumulated = np.zeros_like(previous_shock)
    for index in np.argsort(horizons, kind="stable"):
        step = int(horizons[index])
        if step < previous_step:
            raise ValueError("observation horizons must be nondecreasing")
        shock = baseline.samples[:, :, index] - anchor - step * drift
        gain = _mean_gain(previous_step, step, ratio, half_life, config)
        accumulated += (shock - previous_shock) * gain
        samples[:, :, index] = anchor + step * drift + accumulated
        previous_shock = shock
        previous_step = step
    if not np.isfinite(samples).all():
        raise ValueError("V9-B transformed samples must remain finite")
    updated = dict(meta)
    updated.update(model="v9-b-vol-term-structure", term_structure={
        "half_life_business_days": config.half_life_business_days,
        "gain_bounds": [config.min_gain, config.max_gain],
        "ratio_bounds": [config.min_vol_ratio, config.max_vol_ratio],
    })
    return NumericForecast(samples=samples, metadata=updated)
